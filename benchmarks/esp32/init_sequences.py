#!/usr/bin/env python3
"""Writes the display start-up sequences of the Cranpose ESP32 demo's boards
as a C header, so the benchmark apps send the panels the same bytes.

Usage: init_sequences.py BOARD_RS OUT_H
"""

import re
import sys


def commands(source):
    body = source[source.index("const INIT: &[InitCommand] = &["):]
    body = body[: body.index("\n];")]
    pattern = re.compile(r"InitCommand::new\(\s*(0x[0-9A-Fa-f]+),\s*&\[([^\]]*)\],\s*(\d+),?\s*\)", re.S)
    for command, data, delay in pattern.findall(body):
        values = [v.strip() for v in data.replace("\n", " ").split(",") if v.strip()]
        yield int(command, 16), [int(v, 16) for v in values], int(delay)


def main():
    source = open(sys.argv[1]).read()
    lines = [
        "// Generated by init_sequences.py from " + sys.argv[1].split("/")[-1] + ".",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct { uint8_t command; uint8_t length; uint16_t delay_ms; const uint8_t *data; } init_command_t;",
        "static const init_command_t INIT[] = {",
    ]
    count = 0
    for command, data, delay in commands(source):
        bytes_ = ", ".join(f"0x{b:02X}" for b in data)
        array = f"(const uint8_t[]){{{bytes_}}}" if data else "NULL"
        lines.append(f"    {{0x{command:02X}, {len(data)}, {delay}, {array}}},")
        count += 1
    lines.append("};")
    if count == 0:
        sys.exit("no init commands found")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")


main()

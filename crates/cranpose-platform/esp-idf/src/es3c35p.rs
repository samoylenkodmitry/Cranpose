/// The board.
#[derive(Clone, Copy, Debug)]
pub struct Es3c35p;

impl Board for Es3c35p {
    type Touch = St77922Touch;

    fn open() -> Result<(Panel, St77922Touch), EspError> {
        let panel = Panel::st77922_qspi(WIDTH, HEIGHT, DEFAULT_STRIP_ROWS, DISPLAY, Some(INIT))?;
        let touch = St77922Touch::new(TOUCH)?;
        Ok((panel, touch))
    }
}

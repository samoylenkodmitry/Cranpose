//! Byte-exact comparison against the reference C libopus encoder.
//!
//! This is the strongest correctness evidence in the suite: the expected packets
//! were produced by C libopus built with `--enable-fixed-point`, encoding a
//! 440 Hz sine at each configuration. Matching them byte for byte means this
//! crate's SILK path reproduces the reference encoder's decisions exactly —
//! entropy coding, quantization, gain and LSF search included — not merely that
//! it produces something a decoder accepts.
//!
//! 22 configurations x 20 frames of 20 ms, covering narrowband, mediumband and
//! wideband at complexity 0, 1, 2, 5 and 10, and every sample rate the encoder
//! accepts. The eight at 24 and 48 kHz are the ones where SILK's encoder-side
//! resampler actually resamples; the rest run at SILK's own internal rates,
//! where it is a pass-through.
//!
//! A failure here means the encoder's *decisions* moved. That is not necessarily
//! a bug — an intentional quality change would do it — but it must never happen
//! by accident, and the diff printed on mismatch names the first differing byte.

use opus_pure::Bandwidth;

fn gen_pcm(fs: i32, num_samples: usize) -> Vec<f32> {
    // Integer phase reduction keeps the `sin()` argument inside one period. That
    // is load-bearing: at large arguments the error in a libm sine grows with
    // the argument, and it grew far enough to change the i16 below on some
    // platforms before this reduction was added.
    //
    // What makes the reduced form safe is *not* that `f64::sin` agrees
    // everywhere. It does not — IEEE-754 says nothing about the accuracy of
    // transcendentals, and Apple's arm64 and x86_64 libm differ in the last
    // bits, which is why `tests/common::sin_turns` exists and why every other
    // generator in this suite avoids libm entirely. The safety here comes from
    // the i16 quantisation two lines down: a last-bit disagreement is a relative
    // 1e-16, so about 1e-12 once scaled by 16384, some twelve orders of
    // magnitude below the quantisation step. Measured: this function produces
    // byte-identical output on aarch64 and x86_64 at every rate the suite uses.
    //
    // This file keeps libm rather than switching to `sin_turns` because the
    // expected packets below were produced by C libopus encoding *this* signal.
    // Changing it would mean regenerating all 14 configurations against the C
    // reference, spending the provenance that makes this the strongest evidence
    // in the suite, to buy a margin that is already twelve orders wide.
    (0..num_samples)
        .map(|i| {
            let cycle = (440i64 * i as i64) % fs as i64;
            let phase = cycle as f64 / fs as f64;
            let s = (f64::sin(2.0 * std::f64::consts::PI * phase) * 16384.0) as i16;
            s as f32 / 32768.0
        })
        .collect()
}

fn run_config(fs: i32, bitrate: i32, complexity: i32, c_ref_hex: &[&str], label: &str) {
    run_forced(fs, bitrate, complexity, None, c_ref_hex, label)
}

fn run_forced(
    fs: i32,
    bitrate: i32,
    complexity: i32,
    bandwidth: Option<Bandwidth>,
    c_ref_hex: &[&str],
    label: &str,
) {
    use opus_pure::{Application, OpusEncoder, RateControl};
    let frame_size = fs as usize / 50;
    let total_samples = frame_size * c_ref_hex.len();
    let pcm = gen_pcm(fs, total_samples);

    let mut encoder = OpusEncoder::new(fs, 1, Application::Voip).expect("encoder");
    encoder.complexity = complexity;
    encoder.bitrate_bps = bitrate;
    encoder.rate_control = RateControl::Cbr;
    encoder.force_bandwidth = bandwidth;

    let mut mismatches = 0;
    for (i, ref_hex) in c_ref_hex.iter().enumerate() {
        let c_ref = hex_decode(ref_hex);
        let offset = i * frame_size;
        let mut out = vec![0u8; 1275];
        let n = encoder
            .encode(&pcm[offset..offset + frame_size], frame_size, &mut out)
            .unwrap();
        let pkt = &out[..n];
        if pkt != c_ref.as_slice() {
            mismatches += 1;
            let rust_hex: String = pkt.iter().map(|b| format!("{:02x}", b)).collect();
            println!("[{}] Frame {}: MISMATCH", label, i);
            println!("  C:    {}", ref_hex);
            println!("  Rust: {}", rust_hex);
            for j in 0..pkt.len().min(c_ref.len()) {
                if pkt[j] != c_ref[j] {
                    println!(
                        "  First diff byte {}: C=0x{:02x} Rust=0x{:02x}",
                        j, c_ref[j], pkt[j]
                    );
                    break;
                }
            }
        }
    }
    println!(
        "[{}] {}/{} frames match",
        label,
        c_ref_hex.len() - mismatches,
        c_ref_hex.len()
    );
    assert_eq!(mismatches, 0, "{}: {} frames mismatched", label, mismatches);
}

fn hex_decode(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}


#!/usr/bin/env python3
"""Writes the linker script that moves Cranpose's per-frame code into IRAM.

It reads profiles that `scripts/esp32/sampler` printed (`SPC <pc> <count>`
lines), each with the ELF it ran, picks the framework functions with the
most samples per byte up to a size budget, and writes their sections as
patterns that match in any application: the crate hashes and back-references
of the v0 mangled names become wildcards, and so does the crate that
instantiated a generic function.

Each profile weighs the same: a function's samples count as their share of
the framework samples of its profile, so a list made from a profile of the
demo and one of a screen whose text changes every frame serves both.

With --flash-order, it also writes the section ordering file that puts the
framework functions with samples left out of the budget first in flash, the
hottest per byte first: placed one after another they share the cache with
each other less, and a change elsewhere moves them less.

With --check first, it writes nothing: it names the patterns of list and
order files that matched a function of a base image and match none of
another image, and exits with an error when there is one. A change that
renames, inlines or removes a listed function shows there, before a board
run reads its code from flash.

Usage: hot_code.py BUDGET_KB OUT_LD --profile ELF LOG [--profile ELF LOG ...]
       [--board NAME] [--flash-order OUT_ORDER]
       hot_code.py --check BASE_ELF ELF LIST [LIST ...]
"""

import argparse
import fnmatch
import pathlib
import re
import sys

from profile import functions, samples
from v0_pattern import pattern

# IRAM of the classic ESP32 and of the ESP32-S3. Code there needs no move.
IRAM = [(0x40070000, 0x400C0000), (0x40370000, 0x403E0000)]

def framework_function(name, app_crates):
    return name.startswith("_R") and "cranpose" in name and not any(
        f"{len(crate)}{crate}" in name for crate in app_crates)


class Profile:
    """One profile: the functions of its ELF and the share of the
    framework samples each pattern of them took."""

    def __init__(self, elf, log, app_crates):
        self.starts, self.sizes, self.names = functions(elf, demangle=False)
        hits, _ = samples(log, self.starts, self.sizes)
        if not hits:
            sys.exit(f"{log} has no samples inside functions of {elf}")
        self.rust = [i for i in range(len(self.names)) if self.names[i].startswith("_R")]
        candidates = [
            i for i in hits
            if self.sizes[i] > 0
            and framework_function(self.names[i], app_crates)
            and not any(low <= self.starts[i] < high for low, high in IRAM)
        ]
        total = sum(hits[i] for i in hits if self.names[i].startswith("_R"))
        self.matches = {}
        self.placed = set()
        self.shares = {}
        for i in candidates:
            own = pattern(self.names[i])
            if i not in self.matched(own):
                sys.exit(f"{own} does not match {self.names[i]}")
            self.shares[own] = self.shares.get(own, 0.0) + hits[i] / total

    def matched(self, text):
        """The functions of this ELF that `text` matches."""
        if text not in self.matches:
            regex = re.compile(fnmatch.translate(text))
            self.matches[text] = {j for j in self.rust if regex.match(self.names[j])}
        return self.matches[text]

    def extra(self, text):
        """The bytes `text` adds to what the patterns placed so far match."""
        return sum(self.sizes[j] for j in self.matched(text) - self.placed)

    def place(self, text):
        self.placed |= self.matched(text)


def write_flash_order(out, patterns, profile_count, board):
    """The section ordering file of `patterns`, in their order, for the
    linker's --section-ordering-file: their sections start the flash code.
    A function in the IRAM list matches there first, so it stays in IRAM."""
    lines = [
        f"/* Generated by scripts/esp32/hot_code.py from {profile_count} profiles of {board}.",
        f" * {len(patterns)} patterns in flash, hottest per byte first. See README.md. */",
        ".flash.text :",
        "{",
    ]
    lines += [f"  *(.literal.{p} .text.{p})" for p in patterns]
    lines += ["}", ""]
    out.write_text("\n".join(lines))
    print(f"{out}: {len(patterns)} patterns in flash")


def listed_patterns(text):
    """The function patterns a list or order file names, each once."""
    return list(dict.fromkeys(re.findall(r"\s\.text\.([^\s)]+)\)", text)))


def matches_any(pattern, blob):
    """Whether `pattern` matches a line of `blob`. The lines that hold the
    pattern's longest literal part are the only ones it can match."""
    literal = max(pattern.split("*"), key=len)
    at = blob.find(literal)
    while at >= 0:
        start = blob.rfind("\n", 0, at) + 1
        end = blob.find("\n", at)
        end = len(blob) if end < 0 else end
        if fnmatch.fnmatchcase(blob[start:end], pattern):
            return True
        at = blob.find(literal, end)
    return False


def lost_patterns(patterns, base_names, names):
    """The patterns that match a function of the base image and none of the
    other image's."""
    base, other = "\n".join(base_names), "\n".join(names)
    return [pattern for pattern in patterns if matches_any(pattern, base) and not matches_any(pattern, other)]


def check(arguments):
    """`--check BASE_ELF ELF LIST...`: stops with the patterns the image
    lost against the base image."""
    if len(arguments) < 3:
        sys.exit("usage: hot_code.py --check BASE_ELF ELF LIST [LIST ...]")
    base_names = functions(arguments[0], demangle=False)[2]
    names = functions(arguments[1], demangle=False)[2]
    lost = {}
    for path in arguments[2:]:
        found = lost_patterns(listed_patterns(pathlib.Path(path).read_text()), base_names, names)
        if found:
            lost[path] = found
    if lost:
        lines = [f"{path}: {pattern}" for path, patterns in lost.items() for pattern in patterns]
        sys.exit("patterns that matched the base image and match nothing now:\n" + "\n".join(lines))
    print("every pattern that matched the base image still matches")


def main():
    if sys.argv[1:2] == ["--check"]:
        check(sys.argv[2:])
        return
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("budget_kb", type=float)
    parser.add_argument("out", type=pathlib.Path)
    parser.add_argument("--profile", nargs=2, action="append", required=True,
                        metavar=("ELF", "LOG"), type=pathlib.Path,
                        help="a profile and the ELF it ran; repeat for more")
    parser.add_argument("--board", default="the demo")
    parser.add_argument("--app-crate", action="append", default=["esp32_demo"],
                        help="crates of the profiled app, whose functions stay out")
    parser.add_argument("--flash-order", type=pathlib.Path,
                        help="where to write the order of the sampled functions left in flash")
    args = parser.parse_args()

    profiles = [Profile(elf, log, args.app_crate) for elf, log in args.profile]
    shares = {}
    for profile in profiles:
        for text, share in profile.shares.items():
            shares[text] = shares.get(text, 0.0) + share / len(profiles)
    sizes = {text: max(profile.extra(text) for profile in profiles) for text in shares}
    budget = args.budget_kb * 1024
    patterns, used, covered = [], 0, 0.0
    flash = []
    for text in sorted(shares, key=lambda text: (-shares[text] / sizes[text], text)):
        extra = max(profile.extra(text) for profile in profiles)
        if used + extra <= budget:
            for profile in profiles:
                profile.place(text)
            patterns.append(text)
            used += extra
            covered += shares[text]
        else:
            flash.append(text)
    patterns.sort()
    if args.flash_order:
        write_flash_order(args.flash_order, flash, len(profiles), args.board)

    lines = [
        f"/* Generated by scripts/esp32/hot_code.py from {len(profiles)} profiles of {args.board}.",
        f" * {len(patterns)} patterns, {used / 1024:.0f} KB, took {100 * covered:.0f}% of the samples in Rust code.",
        " * See README.md beside this file. */",
        "SECTIONS",
        "{",
        "  .iram0.cranpose :",
        "  {",
        "    . = ALIGN(4);",
    ]
    lines += [f"    *(.literal.{p} .text.{p})" for p in patterns]
    # No region: ESP-IDF lists its linker scripts after this one, and the
    # linker puts the section in the first executable region, IRAM.
    lines += ["  }", "}", "INSERT AFTER .iram0.text;", ""]
    args.out.write_text("\n".join(lines))
    print(f"{args.out}: {len(patterns)} patterns, {used / 1024:.1f} KB, "
          f"{100 * covered:.1f}% of Rust samples")


if __name__ == "__main__":
    main()
